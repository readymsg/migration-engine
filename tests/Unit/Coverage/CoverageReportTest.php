<?php

declare(strict_types=1);

namespace Tests\Unit\Coverage;

use App\Data\ScrubIssue;
use App\Data\ScrubKind;
use App\Services\Coverage\CoverageReconciler;
use App\Services\Coverage\CoverageReport;
use App\Services\Coverage\SourceElementCounter;
use App\Services\Generate\BlockTypeAssigner;
use PHPUnit\Framework\Attributes\Test;
use Tests\TestCase;

final class CoverageReportTest extends TestCase
{
    private function report(): CoverageReport
    {
        return new CoverageReport(new BlockTypeAssigner, new SourceElementCounter, new CoverageReconciler);
    }

    #[Test]
    public function report_renders_element_and_block_summaries_and_per_page_tables(): void
    {
        $md = $this->report()->render(
            pageMap: [
                'home' => [
                    'root' => ['title' => 'Home'],
                    'content' => [
                        ['type' => 'Hero', 'props' => ['heading' => 'Welcome']],
                        ['type' => 'Text', 'props' => ['body' => 'Some prose here.']],
                        ['type' => 'Image', 'props' => ['src' => 'https://x.jpg', 'alt' => 'banner']],
                    ],
                ],
                'schedule' => [
                    'root' => ['title' => 'Schedule'],
                    'content' => [
                        ['type' => 'PlatformSchedule', 'props' => ['org_id' => 'org-1']],
                    ],
                ],
            ],
            pageTitles: [],
            pageMarkdown: [
                'home' => "# Welcome\n\nSome prose here.\n\n![banner](https://x.jpg)\n",
                'schedule' => "# Old schedule\n\n| team | wins |\n| --- | --- |\n| A | 5 |\n",
            ],
        );

        // TWO distinct summaries — element coverage vs block-type assignment.
        $this->assertStringContainsString('## Site summary — content coverage (element-level)', $md);
        $this->assertStringContainsString('## Site summary — block-type assignment (secondary metric)', $md);
        $this->assertStringContainsString('Migratable coverage:', $md);
        $this->assertStringContainsString('Raw capture rate:', $md);

        // Per-page detail
        $this->assertStringContainsString('### Home', $md);
        $this->assertStringContainsString('### Schedule', $md);
        $this->assertStringContainsString('#### CAPTURED (elements)', $md);
        $this->assertStringContainsString('#### SUPERSEDED (elements)', $md);
        $this->assertStringContainsString('#### DROPPED (elements)', $md);

        // Schedule's source elements are superseded by the platform block.
        $this->assertMatchesRegularExpression('/### Schedule.*regenerated by live PlatformSchedule/s', $md);

        // Platform routing table
        $this->assertStringContainsString('Page routing', $md);
        $this->assertStringContainsString('`Schedule`', $md);
    }

    #[Test]
    public function extra_pages_appear_in_set_aside_table(): void
    {
        $md = $this->report()->render(
            pageMap: ['home' => ['root' => ['title' => 'Home'], 'content' => []]],
            pageTitles: [],
            pageMarkdown: ['home' => ''],
            scrubIssuesBySlug: [],
            extraPages: [
                [
                    'page_title' => 'How To Unsubscribe',
                    'disposition' => 'draft-landing',
                    'reason' => 'nav reconciliation: no PuckOutput (parked at PLAN)',
                    'url' => 'https://example.com/unsubscribe',
                ],
            ],
        );

        $this->assertStringContainsString('Source pages set aside', $md);
        $this->assertStringContainsString('How To Unsubscribe', $md);
        $this->assertStringContainsString('parked at PLAN', $md);
    }

    #[Test]
    public function element_coverage_reflects_captured_and_superseded_but_not_dropped(): void
    {
        // Two prose paragraphs in source; one landed in a Text block,
        // the other is nowhere → 1 captured, 1 dropped → 50.0%.
        $md = $this->report()->render(
            pageMap: [
                'home' => [
                    'root' => ['title' => 'Home'],
                    'content' => [
                        ['type' => 'Text', 'props' => ['body' => 'Alpha paragraph text']],
                    ],
                ],
            ],
            pageTitles: [],
            pageMarkdown: [
                'home' => "Alpha paragraph text.\n\nBeta paragraph nowhere in rebuild.\n",
            ],
        );

        $this->assertStringContainsString('DROPPED **1**', $md);
        $this->assertStringContainsString('Migratable coverage: 50.0%', $md);
        // Raw capture rate must ALSO be present — the transparency line.
        $this->assertStringContainsString('Raw capture rate: 50.0%', $md);
    }

    #[Test]
    public function scrub_sidecar_supersedes_matching_source_elements_not_dropped(): void
    {
        // Element text lives ONLY in a scrub summary (the block was
        // dropped by the SePlatformBlockScrubber). That must classify
        // SUPERSEDED, not DROPPED.
        $md = $this->report()->render(
            pageMap: [
                'home' => [
                    'root' => ['title' => 'Home'],
                    'content' => [
                        ['type' => 'Hero', 'props' => ['heading' => 'welcome']],
                    ],
                ],
            ],
            pageTitles: [],
            pageMarkdown: [
                'home' => "# welcome\n\nSportsEngine for Apple Users\n",
            ],
            scrubIssuesBySlug: [
                'home' => [
                    new ScrubIssue(
                        block_index: 5,
                        component_type: 'ButtonGroup',
                        kind: ScrubKind::SePromoHref,
                        reason: 'SE app-store promo',
                        dropped_content_summary: '3 buttons: SportsEngine for Apple Users -> itunes app store link',
                    ),
                ],
            ],
        );

        $this->assertMatchesRegularExpression('/#### SUPERSEDED.*se_promo_href/is', $md);
        // The SportsEngine string must NOT appear as DROPPED — the scrub
        // sidecar accounts for it.
        $this->assertDoesNotMatchRegularExpression('/#### DROPPED.*SportsEngine for Apple/is', $md);
    }
}
